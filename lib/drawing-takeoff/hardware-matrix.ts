import { createCanvas, loadImage } from "@napi-rs/canvas";
import type { Opening, PageIndex } from "./indexing";
import { locateScheduleTables } from "./schedule-table";
import { renderCrop } from "./pdf-server";

type MatrixColumn = { label: string; x: number };
export type MatrixReading = { mark: string; sourcePage: number; selected: string[]; uncertain: string[] };
export type MatrixResult = { hardwareGroups: Array<Record<string, unknown>>; openingGroups: Array<{mark: string; sourcePage: number; group: string}>; readings: MatrixReading[]; uncertainties: string[] };
const componentLabel = /LOCKSET|CLOSER|HINGE|SILENCER|SWEEP|GASKET|STRIPPING|HOLD\s*OPEN|PUSH\s*HARDWARE|PULL\s*HARDWARE|INDICATOR/i;

/** Paired vertical labels occupy one physical matrix column. Never merge neighboring components. */
export function hardwareMatrixColumns(page: PageIndex): MatrixColumn[] {
  const tables = locateScheduleTables(page).filter(table => table.columns.filter(c => c.key.startsWith("_matrix:") && componentLabel.test(c.box.text)).length >= 4);
  if (tables.length !== 1) return [];
  return tables.flatMap(table => {
    const raw = table.columns.filter(c => c.key.startsWith('_matrix:') && componentLabel.test(c.box.text)).map(c => ({label:c.box.text.trim(),x:c.box.x+c.box.width/2}));
    const result: MatrixColumn[] = [];
    for (const column of raw) {
      const previous = result.at(-1);
      if (previous && /(?:INDICATOR|GASKET)/i.test(previous.label) && /STRIPPING/i.test(column.label) && column.x-previous.x < 18) {
        previous.label += ' / ' + column.label;previous.x=(previous.x+column.x)/2;
      } else result.push({...column});
    }
    return result.length >= 4 ? result : [];
  });
}

export function matrixProfiles(readings: MatrixReading[]): MatrixResult {
  const profiles = new Map<string,string>();
  const hardwareGroups: MatrixResult['hardwareGroups'] = [], openingGroups: MatrixResult['openingGroups'] = [];
  const uncertainties: string[] = [];
  for (const reading of readings) {
    if (reading.uncertain.length) uncertainties.push(`PDF page ${reading.sourcePage}, opening ${reading.mark}: matrix cells need review (${reading.uncertain.join(', ')}).`);
    if (!reading.selected.length) continue;
    const signature = `${reading.sourcePage}:${[...reading.selected].sort().join('|')}`;
    let group = profiles.get(signature);
    if (!group) {
      group = `P${reading.sourcePage}-M${profiles.size + 1}`;profiles.set(signature,group);
      for (const component of reading.selected) hardwareGroups.push({group,name:'Source matrix requirements (generated profile)',brand:'',component,quantity:0,quantityKnown:false,
        sourceRequirement:true,frameModification:'',doorModification:'',doorPrep:'',sourcePage:reading.sourcePage,confidence:.95,
        evidence:`Filled matrix cell under ${component}, PDF page ${reading.sourcePage}, opening ${reading.mark}. The matrix specifies a requirement, not a product model or component quantity. Profile ${group} is generated by the app; it is not a printed hardware set number.`});
    }
    openingGroups.push({mark:reading.mark,sourcePage:reading.sourcePage,group});
  }
  if (hardwareGroups.length) uncertainties.push('Hardware matrix requirements were linked to openings using generated profiles. Component quantities, brands and model selections are unspecified and need confirmation; no purchasing quantities were invented.');
  return {hardwareGroups,openingGroups,readings,uncertainties};
}

/** Sample solid source dots at the intersection of known row/column centers; no model call. */
export async function readHardwareMatrix(bytes: Uint8Array, page: PageIndex, rows: Opening[]): Promise<MatrixResult | null> {
  const columns = hardwareMatrixColumns(page), anchored = rows.filter(row => row.scheduleRowBox);
  if (!columns.length || !anchored.length) return null;
  const x = Math.max(0, Math.min(...columns.map(c=>c.x))-12), right=Math.max(...columns.map(c=>c.x))+12;
  const y = Math.max(0, Math.min(...anchored.map(r=>r.scheduleRowBox!.y))-2);
  const bottom=Math.max(...anchored.map(r=>r.scheduleRowBox!.y+r.scheduleRowBox!.height))+2;
  const crop={x:x*2,y:y*2,width:(right-x)*2,height:(bottom-y)*2};
  const image=await loadImage(await renderCrop(bytes,crop));
  const canvas=createCanvas(image.width,image.height),context=canvas.getContext('2d');context.drawImage(image,0,0);
  const pixels=context.getImageData(0,0,image.width,image.height).data;
  const scale=image.width/crop.width;
  const density=(cx:number,cy:number)=>{
    const radius=Math.max(1,Math.floor(2.5*2*scale));let black=0,total=0;
    for(let py=Math.max(0,Math.round(cy)-radius);py<=Math.min(image.height-1,Math.round(cy)+radius);py++)for(let px=Math.max(0,Math.round(cx)-radius);px<=Math.min(image.width-1,Math.round(cx)+radius);px++){
      const i=(py*image.width+px)*4;total++;if(pixels[i]<80&&pixels[i+1]<80&&pixels[i+2]<80)black++;
    }
    return total?black/total:0;
  };
  const readings=anchored.map(row=>{
    const selected:string[]=[],uncertain:string[]=[];
    const cy=((row.scheduleRowBox!.y+row.scheduleRowBox!.height/2)*2-crop.y)*scale;
    for(const column of columns){
      const cx=(column.x*2-crop.x)*scale;
      // CAD vertical text is often left-aligned within its cell. A compact
      // solid dot may be offset from that text center; grid rules are too thin
      // to fill this patch. Search only inside the same component column.
      let value=0;
      for(let dx=-8;dx<=8;dx+=2)for(let dy=-3;dy<=3;dy+=3)value=Math.max(value,density(cx+dx*2*scale,cy+dy*2*scale));
      if(value>=.85)selected.push(column.label);else if(value>.3)uncertain.push(column.label);
    }
    return {mark:row.mark,sourcePage:page.page,selected,uncertain};
  });
  return matrixProfiles(readings);
}
